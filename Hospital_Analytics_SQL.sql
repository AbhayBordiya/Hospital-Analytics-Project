-- Get all appointments of a specific doctor
DELIMITER //

create procedure GetDoctorAppointments(in d_id varchar(10))
begin
    select 
        a.appointment_id,
        a.appointment_date,
        a.status,
        a.reason_for_visit,
        p.first_name,
        p.last_name
    from appointments a
    join patients p 
        on a.patient_id = p.patient_id
    where a.doctor_id = d_id;
end //

DELIMITER ;
call GetDoctorAppointments ("D001");

