-- Get all details of a patient by their patient ID
DELIMITER //

create procedure GetPatientDetails(in p_id varchar(20))
begin
    select 
        p.patient_id,p.first_name,p.last_name,p.gender,p.age,p.medical_condition,p.insurance_provider,
        a.appointment_date,a.status,a.reason_for_visit,
        b.final_amount,b.payment_status
    from patients p
    left join appointments a ON p.patient_id = a.patient_id
    left join billing b ON p.patient_id = b.patient_id
    where p.patient_id = p_id;
end //

DELIMITER ;

