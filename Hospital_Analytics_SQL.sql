-- Create a view for doctor performance summary
create view doctors_performance as
select 
d.doctor_id,d.full_name as doctor_name,d.specialization,d.rating,d.years_experience,
count(t.treatment_id) as Total_treatments,round(sum(t.cost),2)as total_revenue,round(avg(t.cost),2)as avg_treatment_cost
from doctors d
join treatments t 
	on d.doctor_id = t.doctor_id
group by d.doctor_id,d.full_name,d.specialization,d.rating,d.years_experience
order by total_revenue desc; 
